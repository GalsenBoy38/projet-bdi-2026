);

-- Nature d'une offre réservable (chambre simple, chambre double, emplacement, bungalow…).
CREATE TABLE TYPE_HEBERGEMENT (
  id_type_hebergement            NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  libelle_type_hebergement       VARCHAR2(60) NOT NULL,
  CONSTRAINT PK_TYPE_HEBERGEMENT PRIMARY KEY (id_type_hebergement),
  CONSTRAINT UK_TYPE_HEBERGEMENT_LIBELLE_TYPE_HEBERGEMENT UNIQUE (libelle_type_hebergement)

  CONSTRAINT UK_BON_HEBERGEMENT_NUMERO_BON UNIQUE (numero_bon),
  CONSTRAINT FK_BON_HEBERGEMENT_ID_RESERVATION FOREIGN KEY (id_reservation) REFERENCES RESERVATION (id_reservation) ON DELETE CASCADE,
  CONSTRAINT FK_BON_HEBERGEMENT_ID_HEBERGEMENT FOREIGN KEY (id_hebergement) REFERENCES HEBERGEMENT (id_hebergement) ON DELETE CASCADE,

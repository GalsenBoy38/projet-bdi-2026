-- Réservation définitive de Pass et d'hébergements pour un même festival.
CREATE TABLE RESERVATION (
  id_reservation                 NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  numero_reservation             VARCHAR2(20) NOT NULL,
  statut_reservation             VARCHAR2(10) NOT NULL,
  date_annulation                TIMESTAMP,
  motif_annulation               VARCHAR2(300),
  id_commande                    NUMBER(10) NOT NULL,
  id_festival                    NUMBER(10) NOT NULL,
  CONSTRAINT PK_RESERVATION PRIMARY KEY (id_reservation),
  CONSTRAINT UK_RESERVATION_NUMERO_RESERVATION UNIQUE (numero_reservation),
  CONSTRAINT FK_RESERVATION_ID_COMMANDE FOREIGN KEY (id_commande) REFERENCES COMMANDE (id_commande),
  CONSTRAINT FK_RESERVATION_ID_FESTIVAL FOREIGN KEY (id_festival) REFERENCES FESTIVAL (id_festival),
  CONSTRAINT CK_RESERVATION_1 CHECK (statut_reservation IN ('CONFIRMEE','ANNULEE')),
  CONSTRAINT CK_RESERVATION_2 CHECK ((statut_reservation = 'CONFIRMEE' AND date_annulation IS NULL) OR (statut_reservation = 'ANNULEE' AND date_annulation IS NOT NULL)),
  CONSTRAINT UK_RESERVATION_3 UNIQUE (id_commande, id_festival)
);

-- Droit d'accès individuel à un festival pour toute sa durée, édité en PDF (composant de la réservation).
CREATE TABLE PASS (
  id_pass                        NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  numero_pass                    VARCHAR2(20) NOT NULL,
  prix_paye                      NUMBER(8,2) NOT NULL,
  date_emission_pass             TIMESTAMP NOT NULL,
  id_reservation                 NUMBER(10) NOT NULL,
  CONSTRAINT PK_PASS PRIMARY KEY (id_pass),
  CONSTRAINT UK_PASS_NUMERO_PASS UNIQUE (numero_pass),
  CONSTRAINT FK_PASS_ID_RESERVATION FOREIGN KEY (id_reservation) REFERENCES RESERVATION (id_reservation) ON DELETE CASCADE,
  CONSTRAINT CK_PASS_1 CHECK (prix_paye >= 0)

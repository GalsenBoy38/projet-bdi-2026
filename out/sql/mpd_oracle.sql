  CONSTRAINT CK_HEBERGEMENT_3 CHECK (statut_hebergement IN ('PUBLIE','RETIRE'))
);

-- Fait qu'un hébergement inclut une option.
CREATE TABLE HEBERGEMENT_OPTION (

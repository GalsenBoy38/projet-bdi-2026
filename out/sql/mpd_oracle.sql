-- Région administrative française (dont outre-mer).
CREATE TABLE REGION (
  id_region                      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nom_region                     VARCHAR2(60) NOT NULL,
  CONSTRAINT PK_REGION PRIMARY KEY (id_region),
  CONSTRAINT UK_REGION_NOM_REGION UNIQUE (nom_region)
);

-- Département français identifié par son code officiel (01…95, 2A, 2B, 971…).
CREATE TABLE DEPARTEMENT (
  code_departement               VARCHAR2(3) NOT NULL,
  nom_departement                VARCHAR2(60) NOT NULL,
  id_region                      NUMBER(10) NOT NULL,
  CONSTRAINT PK_DEPARTEMENT PRIMARY KEY (code_departement),
  CONSTRAINT FK_DEPARTEMENT_ID_REGION FOREIGN KEY (id_region) REFERENCES REGION (id_region)
);

-- Commune française identifiée par son code INSEE, avec son centroïde géographique.
CREATE TABLE COMMUNE (
  code_insee                     CHAR(5) NOT NULL,
  nom_commune                    VARCHAR2(100) NOT NULL,
  latitude_commune               NUMBER(9,6),
  longitude_commune              NUMBER(9,6),
  code_departement               VARCHAR2(3) NOT NULL,
  CONSTRAINT PK_COMMUNE PRIMARY KEY (code_insee),
  CONSTRAINT FK_COMMUNE_CODE_DEPARTEMENT FOREIGN KEY (code_departement) REFERENCES DEPARTEMENT (code_departement),
  CONSTRAINT CK_COMMUNE_1 CHECK (latitude_commune BETWEEN -90 AND 90),
  CONSTRAINT CK_COMMUNE_2 CHECK (longitude_commune BETWEEN -180 AND 180)
);

-- Grand domaine artistique d'une manifestation (type de festival).
CREATE TABLE DOMAINE (
  id_domaine                     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  libelle_domaine                VARCHAR2(80) NOT NULL,
  CONSTRAINT PK_DOMAINE PRIMARY KEY (id_domaine),
  CONSTRAINT UK_DOMAINE_LIBELLE_DOMAINE UNIQUE (libelle_domaine)
);

-- Style précisant le domaine (ex. Jazz, blues et musiques improvisées) ; indépendant du domaine dans la source.
CREATE TABLE SOUS_DOMAINE (
  id_sous_domaine                NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  libelle_sous_domaine           VARCHAR2(80) NOT NULL,
  CONSTRAINT PK_SOUS_DOMAINE PRIMARY KEY (id_sous_domaine),
  CONSTRAINT UK_SOUS_DOMAINE_LIBELLE_SOUS_DOMAINE UNIQUE (libelle_sous_domaine)
);

-- Rythme de tenue d'une manifestation.
CREATE TABLE PERIODICITE (
  id_periodicite                 NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  libelle_periodicite            VARCHAR2(40) NOT NULL,
  CONSTRAINT PK_PERIODICITE PRIMARY KEY (id_periodicite),
  CONSTRAINT UK_PERIODICITE_LIBELLE_PERIODICITE UNIQUE (libelle_periodicite)
);

-- Organisme public pouvant soutenir un festival (Ministère de la culture, CNC, CNL, CNV).
CREATE TABLE ORGANISME_SOUTIEN (
  id_organisme                   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  sigle_organisme                VARCHAR2(10) NOT NULL,
  libelle_organisme              VARCHAR2(80) NOT NULL,
  CONSTRAINT PK_ORGANISME_SOUTIEN PRIMARY KEY (id_organisme),
  CONSTRAINT UK_ORGANISME_SOUTIEN_SIGLE_ORGANISME UNIQUE (sigle_organisme)
);

-- Compte d'authentification interne au Back-Office FestiBed.
CREATE TABLE COMPTE_INTERNE (
  id_compte                      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  email_compte                   VARCHAR2(254) NOT NULL,
  mot_de_passe_hash              VARCHAR2(100) NOT NULL,
  nom_compte                     VARCHAR2(80) NOT NULL,
  prenom_compte                  VARCHAR2(80) NOT NULL,
  telephone_compte               VARCHAR2(20),
  date_creation_compte           TIMESTAMP NOT NULL,
  CONSTRAINT PK_COMPTE_INTERNE PRIMARY KEY (id_compte),
  CONSTRAINT UK_COMPTE_INTERNE_EMAIL_COMPTE UNIQUE (email_compte)
);

-- Compte interne responsable d'un ou plusieurs festivals.
CREATE TABLE ORGANISATEUR (
  id_compte                      NUMBER(10) NOT NULL,
  nom_structure                  VARCHAR2(150),
  CONSTRAINT PK_ORGANISATEUR PRIMARY KEY (id_compte),
  CONSTRAINT FK_ORGANISATEUR_ID_COMPTE FOREIGN KEY (id_compte) REFERENCES COMPTE_INTERNE (id_compte) ON DELETE CASCADE
);

-- Manifestation proposée dans FestiBed, issue du jeu public ou créée/complétée par un Organisateur.
CREATE TABLE FESTIVAL (
  id_festival                    NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  code_identification            VARCHAR2(10),
  nom_festival                   VARCHAR2(200) NOT NULL,
  site_web_festival              VARCHAR2(300),
  date_creation_festival         DATE,
  mois_habituel_debut            NUMBER(2) NOT NULL,
  date_debut_source              DATE,
  date_fin_source                DATE,
  num_edition_2018               NUMBER(4),
  num_edition_2019               NUMBER(4),
  montant_soutien_2017           NUMBER(10),
  commentaire_festival           VARCHAR2(4000),
  code_postal_festival           VARCHAR2(5) NOT NULL,
  code_insee                     CHAR(5) NOT NULL,
  id_domaine                     NUMBER(10) NOT NULL,
  id_sous_domaine                NUMBER(10),
  id_periodicite                 NUMBER(10),
  id_organisateur                NUMBER(10),
  date_debut_festival            DATE,
  date_fin_festival              DATE,
  prix_pass                      NUMBER(8,2),
  quota_pass                     NUMBER(6) DEFAULT 0 NOT NULL,
  nb_pass_reserves               NUMBER(6) DEFAULT 0 NOT NULL,
  statut_festival                VARCHAR2(10) NOT NULL,
  description_festival           VARCHAR2(4000),
  version_festival               NUMBER(10) DEFAULT 0 NOT NULL,
  pass_disponibles               GENERATED ALWAYS AS (quota_pass - nb_pass_reserves) VIRTUAL,
  CONSTRAINT PK_FESTIVAL PRIMARY KEY (id_festival),
  CONSTRAINT UK_FESTIVAL_CODE_IDENTIFICATION UNIQUE (code_identification),
  CONSTRAINT FK_FESTIVAL_CODE_INSEE FOREIGN KEY (code_insee) REFERENCES COMMUNE (code_insee),
  CONSTRAINT FK_FESTIVAL_ID_DOMAINE FOREIGN KEY (id_domaine) REFERENCES DOMAINE (id_domaine),
  CONSTRAINT FK_FESTIVAL_ID_SOUS_DOMAINE FOREIGN KEY (id_sous_domaine) REFERENCES SOUS_DOMAINE (id_sous_domaine),
  CONSTRAINT FK_FESTIVAL_ID_PERIODICITE FOREIGN KEY (id_periodicite) REFERENCES PERIODICITE (id_periodicite),
  CONSTRAINT FK_FESTIVAL_ID_ORGANISATEUR FOREIGN KEY (id_organisateur) REFERENCES ORGANISATEUR (id_compte),
  CONSTRAINT CK_FESTIVAL_1 CHECK (mois_habituel_debut BETWEEN 1 AND 12),
  CONSTRAINT CK_FESTIVAL_2 CHECK (date_fin_festival >= date_debut_festival),
  CONSTRAINT CK_FESTIVAL_3 CHECK (quota_pass >= 0),
  CONSTRAINT CK_FESTIVAL_4 CHECK (nb_pass_reserves BETWEEN 0 AND quota_pass),
  CONSTRAINT CK_FESTIVAL_5 CHECK (prix_pass >= 0),
  CONSTRAINT CK_FESTIVAL_6 CHECK (statut_festival IN ('BROUILLON','ACTIF','DESACTIVE')),
  CONSTRAINT CK_FESTIVAL_7 CHECK (statut_festival <> 'ACTIF' OR (date_debut_festival IS NOT NULL AND date_fin_festival IS NOT NULL AND prix_pass IS NOT NULL))
);

-- Fait qu'un festival se déroule aussi dans d'autres communes que sa commune principale.
CREATE TABLE FESTIVAL_COMMUNE (
  id_festival                    NUMBER(10) NOT NULL,
  code_insee                     CHAR(5) NOT NULL,
  CONSTRAINT PK_FESTIVAL_COMMUNE PRIMARY KEY (id_festival, code_insee),
  CONSTRAINT FK_FESTIVAL_COMMUNE_ID_FESTIVAL FOREIGN KEY (id_festival) REFERENCES FESTIVAL (id_festival) ON DELETE CASCADE,
  CONSTRAINT FK_FESTIVAL_COMMUNE_CODE_INSEE FOREIGN KEY (code_insee) REFERENCES COMMUNE (code_insee) ON DELETE CASCADE
);

-- Fait qu'un organisme a soutenu un festival une année donnée.
CREATE TABLE SOUTIEN (
  id_festival                    NUMBER(10) NOT NULL,
  id_organisme                   NUMBER(10) NOT NULL,
  annee_soutien                  NUMBER(4) NOT NULL,
  CONSTRAINT PK_SOUTIEN PRIMARY KEY (id_festival, id_organisme, annee_soutien),
  CONSTRAINT FK_SOUTIEN_ID_FESTIVAL FOREIGN KEY (id_festival) REFERENCES FESTIVAL (id_festival) ON DELETE CASCADE,
  CONSTRAINT FK_SOUTIEN_ID_ORGANISME FOREIGN KEY (id_organisme) REFERENCES ORGANISME_SOUTIEN (id_organisme) ON DELETE CASCADE,
  CONSTRAINT CK_SOUTIEN_1 CHECK (annee_soutien BETWEEN 1990 AND 2100)
);

-- Catégorie réglementaire d'établissement ; détermine la nature de ses unités d'accueil.
CREATE TABLE TYPOLOGIE_ETABLISSEMENT (
  code_typologie                 VARCHAR2(20) NOT NULL,
  libelle_typologie              VARCHAR2(60) NOT NULL,
  unite_accueil                  VARCHAR2(30) NOT NULL,
  CONSTRAINT PK_TYPOLOGIE_ETABLISSEMENT PRIMARY KEY (code_typologie),
  CONSTRAINT UK_TYPOLOGIE_ETABLISSEMENT_LIBELLE_TYPOLOGIE UNIQUE (libelle_typologie)
);

-- Niveau de classement officiel d'un établissement.
CREATE TABLE CLASSEMENT (
  id_classement                  NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  libelle_classement             VARCHAR2(40) NOT NULL,
  nb_etoiles                     NUMBER(1),
  CONSTRAINT PK_CLASSEMENT PRIMARY KEY (id_classement),
  CONSTRAINT UK_CLASSEMENT_LIBELLE_CLASSEMENT UNIQUE (libelle_classement),
  CONSTRAINT CK_CLASSEMENT_1 CHECK (nb_etoiles BETWEEN 1 AND 5)
);

-- Compte interne responsable d'un ou plusieurs établissements d'hébergement.
CREATE TABLE HEBERGEUR (
  id_compte                      NUMBER(10) NOT NULL,
  raison_sociale                 VARCHAR2(150),
  CONSTRAINT PK_HEBERGEUR PRIMARY KEY (id_compte),
  CONSTRAINT FK_HEBERGEUR_ID_COMPTE FOREIGN KEY (id_compte) REFERENCES COMPTE_INTERNE (id_compte) ON DELETE CASCADE
);

-- Lieu physique d'hébergement collectif classé, répertorié dans le jeu de données public.
CREATE TABLE ETABLISSEMENT (
  id_etablissement               NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nom_commercial                 VARCHAR2(200) NOT NULL,
  adresse_etablissement          VARCHAR2(300) NOT NULL,
  code_postal_etablissement      VARCHAR2(5) NOT NULL,
  site_internet                  VARCHAR2(300),
  date_classement                DATE NOT NULL,
  classement_proroge             NUMBER(1) DEFAULT 0 NOT NULL,
  capacite_accueil               NUMBER(6) NOT NULL,
  nb_unites                      NUMBER(5) NOT NULL,
  categorie_camping              VARCHAR2(10),
  mention_village                VARCHAR2(30),
  type_sejour                    VARCHAR2(30),
  code_insee                     CHAR(5) NOT NULL,
  code_typologie                 VARCHAR2(20) NOT NULL,
  id_classement                  NUMBER(10) NOT NULL,
  id_hebergeur                   NUMBER(10),
  latitude_etablissement         NUMBER(9,6),
  longitude_etablissement        NUMBER(9,6),
  note_moyenne_etablissement     NUMBER(3,2),
  nb_notes_etablissement         NUMBER(8) DEFAULT 0 NOT NULL,
  CONSTRAINT PK_ETABLISSEMENT PRIMARY KEY (id_etablissement),
  CONSTRAINT FK_ETABLISSEMENT_CODE_INSEE FOREIGN KEY (code_insee) REFERENCES COMMUNE (code_insee),
  CONSTRAINT FK_ETABLISSEMENT_CODE_TYPOLOGIE FOREIGN KEY (code_typologie) REFERENCES TYPOLOGIE_ETABLISSEMENT (code_typologie),
  CONSTRAINT FK_ETABLISSEMENT_ID_CLASSEMENT FOREIGN KEY (id_classement) REFERENCES CLASSEMENT (id_classement),
  CONSTRAINT FK_ETABLISSEMENT_ID_HEBERGEUR FOREIGN KEY (id_hebergeur) REFERENCES HEBERGEUR (id_compte),
  CONSTRAINT CK_ETABLISSEMENT_1 CHECK (classement_proroge IN (0,1)),
  CONSTRAINT CK_ETABLISSEMENT_2 CHECK (capacite_accueil > 0),
  CONSTRAINT CK_ETABLISSEMENT_3 CHECK (nb_unites >= 0),
  CONSTRAINT CK_ETABLISSEMENT_4 CHECK (categorie_camping IS NULL OR (code_typologie = 'CAMPING' AND categorie_camping IN ('TOURISME','LOISIRS'))),
  CONSTRAINT CK_ETABLISSEMENT_5 CHECK (mention_village IS NULL OR (code_typologie = 'VILLAGE_VACANCES' AND mention_village IN ('NON','HEBERGEMENT_DISPERSE','HEBERGEMENT_LEGER','HEBERGEMENT_LEGER_ET_DISPERSE'))),
  CONSTRAINT CK_ETABLISSEMENT_6 CHECK (type_sejour IS NULL OR (code_typologie = 'VILLAGE_VACANCES' AND type_sejour IN ('FORMULE_PENSION','FORMULE_LOCATION','FORMULE_LOCATION_PENSION'))),
  CONSTRAINT CK_ETABLISSEMENT_7 CHECK (note_moyenne_etablissement BETWEEN 1 AND 5),
  CONSTRAINT CK_ETABLISSEMENT_8 CHECK (nb_notes_etablissement >= 0),
  CONSTRAINT UK_ETABLISSEMENT_9 UNIQUE (nom_commercial, adresse_etablissement, code_postal_etablissement)
);

-- Utilisateur du FrontOffice, authentifié par un réseau social ou compte de test du peuplement.
CREATE TABLE FESTIVALIER (
  id_festivalier                 NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  email_festivalier              VARCHAR2(254) NOT NULL,
  nom_festivalier                VARCHAR2(80) NOT NULL,
  prenom_festivalier             VARCHAR2(80) NOT NULL,
  fournisseur_auth               VARCHAR2(10) NOT NULL,
  id_externe                     VARCHAR2(128) NOT NULL,
  compte_test                    NUMBER(1) DEFAULT 0 NOT NULL,
  date_inscription               TIMESTAMP NOT NULL,
  CONSTRAINT PK_FESTIVALIER PRIMARY KEY (id_festivalier),
  CONSTRAINT UK_FESTIVALIER_EMAIL_FESTIVALIER UNIQUE (email_festivalier),
  CONSTRAINT CK_FESTIVALIER_1 CHECK (fournisseur_auth IN ('GOOGLE','FACEBOOK','GITHUB','TEST')),
  CONSTRAINT CK_FESTIVALIER_2 CHECK (compte_test IN (0,1)),
  CONSTRAINT UK_FESTIVALIER_3 UNIQUE (fournisseur_auth, id_externe),

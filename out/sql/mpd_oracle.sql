  CONSTRAINT FK_HEBERGEMENT_OPTION_ID_OPTION FOREIGN KEY (id_option) REFERENCES OPTION_HEBERGEMENT (id_option) ON DELETE CASCADE
);

-- Photographie illustrant un hébergement (composant de l'hébergement).

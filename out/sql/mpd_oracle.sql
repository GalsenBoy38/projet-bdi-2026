-- Intervalle de nuits [début, fin[ pendant lequel l'hébergeur ouvre un hébergement à FestiBed (composant de l'hébergement).
CREATE TABLE PERIODE_DISPONIBILITE (
  id_periode                     NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  date_debut_dispo               DATE NOT NULL,
  date_fin_dispo                 DATE NOT NULL,
  id_hebergement                 NUMBER(10) NOT NULL,
  CONSTRAINT PK_PERIODE_DISPONIBILITE PRIMARY KEY (id_periode),
  CONSTRAINT FK_PERIODE_DISPONIBILITE_ID_HEBERGEMENT FOREIGN KEY (id_hebergement) REFERENCES HEBERGEMENT (id_hebergement) ON DELETE CASCADE,

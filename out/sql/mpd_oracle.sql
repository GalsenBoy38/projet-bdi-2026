-- Sélection temporaire d'un festivalier, éventuellement anonyme.
CREATE TABLE PANIER (
  id_panier                      NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  jeton_session                  VARCHAR2(36) NOT NULL,
  date_creation_panier           TIMESTAMP NOT NULL,
  date_maj_panier                TIMESTAMP NOT NULL,
  id_festivalier                 NUMBER(10),
  CONSTRAINT PK_PANIER PRIMARY KEY (id_panier),
  CONSTRAINT UK_PANIER_JETON_SESSION UNIQUE (jeton_session),
  CONSTRAINT FK_PANIER_ID_FESTIVALIER FOREIGN KEY (id_festivalier) REFERENCES FESTIVALIER (id_festivalier)
);

-- Élément du panier : pour un festival, le nombre de Pass demandés et les hébergements choisis (composant du panier).
CREATE TABLE SELECTION (
  id_selection                   NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nb_pass_selection              NUMBER(3) NOT NULL,
  date_ajout                     TIMESTAMP NOT NULL,
  date_expiration                TIMESTAMP NOT NULL,
  id_panier                      NUMBER(10) NOT NULL,
  id_festival                    NUMBER(10) NOT NULL,
  CONSTRAINT PK_SELECTION PRIMARY KEY (id_selection),
  CONSTRAINT FK_SELECTION_ID_PANIER FOREIGN KEY (id_panier) REFERENCES PANIER (id_panier) ON DELETE CASCADE,
  CONSTRAINT FK_SELECTION_ID_FESTIVAL FOREIGN KEY (id_festival) REFERENCES FESTIVAL (id_festival) ON DELETE CASCADE,
  CONSTRAINT CK_SELECTION_1 CHECK (nb_pass_selection > 0),
  CONSTRAINT CK_SELECTION_2 CHECK (date_expiration > date_ajout),
  CONSTRAINT UK_SELECTION_3 UNIQUE (id_panier, id_festival)
);

-- Fait qu'une sélection inclut un hébergement.
CREATE TABLE SELECTION_HEBERGEMENT (
  id_selection                   NUMBER(10) NOT NULL,
  id_hebergement                 NUMBER(10) NOT NULL,
  CONSTRAINT PK_SELECTION_HEBERGEMENT PRIMARY KEY (id_selection, id_hebergement),
  CONSTRAINT FK_SELECTION_HEBERGEMENT_ID_SELECTION FOREIGN KEY (id_selection) REFERENCES SELECTION (id_selection) ON DELETE CASCADE,
  CONSTRAINT FK_SELECTION_HEBERGEMENT_ID_HEBERGEMENT FOREIGN KEY (id_hebergement) REFERENCES HEBERGEMENT (id_hebergement) ON DELETE CASCADE
);

-- Résultat de la validation d'un panier ; regroupe une réservation par festival et porte le paiement.
CREATE TABLE COMMANDE (
